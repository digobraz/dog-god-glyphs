import { chromium } from 'playwright';
const S=process.argv[2];
const b=await chromium.launch(); const p=await (await b.newContext({viewport:{width:390,height:780},deviceScaleFactor:2})).newPage();
await p.goto('http://localhost:8080/heroglyph/breed?dev=1'); await p.waitForTimeout(2500); await p.getByText('Only necessary').click(); await p.waitForTimeout(600);
await p.screenshot({path:S+'/1-pred.png'});
await p.locator('.pt-sil').first().click(); await p.waitForTimeout(500);
await p.screenshot({path:S+'/2-po-patronovi.png'});
await p.locator('.hf-cta').dispatchEvent('click'); await p.waitForTimeout(250);
await p.screenshot({path:S+'/3-po-cta.png'});
console.log('need',await p.locator('.pt-need').count(), 'popup', await p.locator('.pt-breedpanel').count());
await b.close();
